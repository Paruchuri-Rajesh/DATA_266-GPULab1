"""
Zips one member's run artifacts so they can leave the GPU Lab machine
(lab machines are wiped after each session).

  python tools/pack_results.py --member sivasurya_chandran               # everything, all tasks
  python tools/pack_results.py --member sivasurya_chandran --task task3_gan --no_state   # final weights + logs only_gan

Includes checkpoints/ (with train_state.pt, needed to --resume in a later
session), logs/, outputs/, config, deliverables and the executed notebooks.
Excludes data_processed/ (regenerated by src/preprocess.py) and raw datasets.
Writes backups/<member>_<task|all>_<timestamp>.zip. Upload it to Google Drive.
"""
import argparse
import os
import time
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TASKS = ("task1_llm", "task2_sentiment", "task3_gan")
SKIP_DIRS = {"data_processed", "data_smoketest", "__pycache__", "submission"}

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--member", required=True)
    ap.add_argument("--task", choices=TASKS)
    ap.add_argument("--with_submission", action="store_true", help="also include task3 submission/ (about 7K JPEGs)")
    ap.add_argument("--no_state", action="store_true", help="leave out train_state.pt, *_last.pt and select_tmp/ (no resume; much smaller)")
    a = ap.parse_args()
    os.makedirs(os.path.join(ROOT, "backups"), exist_ok=True)
    out = os.path.join(ROOT, "backups", f"{a.member}_{a.task or 'all'}_{time.strftime('%Y%m%d_%H%M')}.zip")
    skip = SKIP_DIRS - ({"submission"} if a.with_submission else set()) | ({"select_tmp"} if a.no_state else set())
    n = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for task in [a.task] if a.task else TASKS:
            base = os.path.join(ROOT, task, a.member)
            for dirpath, dirnames, files in os.walk(base):
                dirnames[:] = [d for d in dirnames if d not in skip]
                for f in files:
                    if a.no_state and (f == "train_state.pt" or f.endswith("_last.pt")):
                        continue
                    p = os.path.join(dirpath, f)
                    zf.write(p, os.path.relpath(p, ROOT))
                    n += 1
        rep = os.path.join(ROOT, "reproducibility")
        for dirpath, _, files in os.walk(rep):
            for f in files:
                p = os.path.join(dirpath, f)
                zf.write(p, os.path.relpath(p, ROOT))
                n += 1
    print(f"{n} files -> {out} ({os.path.getsize(out) / 2**20:.1f} MB)")
    print("Unzip it at the repo root in the next session to restore checkpoints/train_state.pt and continue with --resume.")
